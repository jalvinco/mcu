function countryFromLocale(): string | undefined {
  if (typeof navigator === 'undefined') return undefined;
  const locales = navigator.languages?.length ? navigator.languages : [navigator.language];

  for (const locale of locales) {
    const region = locale
      .split('-')
      .slice(1)
      .find((part) => /^[A-Za-z]{2}$/.test(part))
      ?.toUpperCase();
    if (region) return region;
  }
}

export function getViewerCountryCode(): string | undefined {
  const browserTimeZone = Intl.DateTimeFormat().resolvedOptions().timeZone || 'UTC';
  return exactTimeZoneMarkets[browserTimeZone]
    ?? timeZonePrefixes.find(([prefix]) => browserTimeZone.startsWith(prefix))?.[1]
    ?? countryFromLocale();
}

export function isTimeZoneForCountry(timeZone: string, countryCode: string): boolean {
  return exactTimeZoneMarkets[timeZone] === countryCode
    || timeZonePrefixes.some(([prefix, code]) => code === countryCode && timeZone.startsWith(prefix));
}
